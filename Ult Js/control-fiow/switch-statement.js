let dayNumber=5;
switch(dayNumber){
    case 1:
        console.log("Monday");
        break;
    case 2:
        console.log("Tuesday");
        break;
    case 3:
        console.log("Wednesday");
        break;

    case 4:
        console.log("Thursday");
        break;
    case 5:
        console.log("Super Friday");
        break;
    default:
        console.log("Weekend od Invalid Day");
        break;
    
}